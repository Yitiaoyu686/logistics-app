function t(dayOffset = 0, hourOffset = 0) {
  const d = new Date(BASE_TIME.getTime() + dayOffset * 24 * 3600 * 1000 + hourOffset * 3600 * 1000);
  return d.toISOString();
}

function insert(table, row) {
  const keys = Object.keys(row);
  const sql = `INSERT INTO ${table} (${keys.join(',')}) VALUES (${keys.map(() => '?').join(',')})`;
  db.prepare(sql).run(...keys.map((key) => row[key]));
}

function hasLetterAndDigit(code) {
  return /[A-Z]/.test(code) && /\d/.test(code);
}

function generateShortCode(existingSet) {
  const alphabet = 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
  for (let i = 0; i < 3000; i += 1) {
    let code = '';
    for (let j = 0; j < 4; j += 1) {
      code += alphabet[Math.floor(Math.random() * alphabet.length)];
    }
    if (!hasLetterAndDigit(code)) continue;
    if (!existingSet.has(code)) {
      existingSet.add(code);
      return code;
    }
  }
  throw new Error('无法生成不重复客户短码');
}

