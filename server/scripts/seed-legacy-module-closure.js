function seed() {
  const data = buildDataset();

  const tx = db.transaction(() => {
    cleanup();

    data.clients.forEach((row) => insert('clients', row));
    data.masterOrders.forEach((row) => insert('master_orders', row));
    data.jobs.forEach((row) => insert('jobs', row));
    data.shippingUnits.forEach((row) => insert('shipping_units', row));
    data.subOrders.forEach((row) => insert('sub_orders', row));
    data.orderItems.forEach((row) => insert('order_items', row));
    data.expressPackages.forEach((row) => insert('express_packages', row));
    data.inboundRecords.forEach((row) => insert('inbound_records', row));
    data.stockItems.forEach((row) => insert('stock_items', row));
    data.transferOrders.forEach((row) => insert('transfer_orders', row));
    data.transferItems.forEach((row) => insert('transfer_items', row));
    data.returnRecords.forEach((row) => insert('return_records', row));
    data.noOrderExpress.forEach((row) => insert('no_order_express', row));
    data.deliveryOrders.forEach((row) => insert('delivery_orders', row));
    data.deliveryItems.forEach((row) => insert('delivery_order_items', row));
    data.feeRecords.forEach((row) => insert('fee_records', row));
    data.logisticsRecords.forEach((row) => insert('logistics_records', row));

    db.prepare(`
      UPDATE clients
      SET totalOrders = (
        SELECT COUNT(*) FROM master_orders m WHERE m.customerId = clients.id
      ),
      lastOrderTime = (
        SELECT MAX(createdAt) FROM master_orders m WHERE m.customerId = clients.id
      )
      WHERE id LIKE ?
    `).run(`${TAG}-CUST-%`);
  });

  tx();

  return data;
}

